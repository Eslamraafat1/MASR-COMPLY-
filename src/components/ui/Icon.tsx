/** Resolve an icon by its string name (data files store names, not components). */
export function Icon({ name, className, size = 22, strokeWidth = 1.75 }: { name: string; className?: string; size?: number; strokeWidth?: number }) {
  const C = ICONS[name] ?? CircleHelp;
  return <C aria-hidden="true" className={className} size={size} strokeWidth={strokeWidth} />;
}
